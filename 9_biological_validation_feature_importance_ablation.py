#!/usr/bin/env python
"""
CRLP downstream analysis:
1) Biological validation of gene-pair predictions
2) Feature importance (permutation; optional SHAP)
3) Feature-group ablation experiments

IMPORTANT SCIENTIFIC SCOPE
--------------------------
The existing nine-model GSE90546 script is a profile-level self-supervised
representation-learning pipeline. It is NOT a supervised gene-pair
compensation classifier. This script therefore builds a separate, explicitly
label-supervised gene-pair classifier from independently curated evidence
labels. It never converts untested pairs into negative labels.

Required project files (defaults assume this script is placed in BA/):
    features/candidate_gene_pairs.csv.gz
    preprocessed/compensation_training_pairs.csv

Optional biological-validation files:
    preprocessed/gene_function_terms.csv
        columns: gene, term
    preprocessed/external_validation_pairs.csv
        columns: target_gene, candidate_gene, label, plus same feature columns
    preprocessed/celltype_predictions.csv
        columns: target_gene, candidate_gene, cell_type, prediction_score

Optional input for precomputed predictions is not required: predictions are
generated by the final pair classifier.

Outputs are written to:
    downstream_validation/

Run:
    python 9_biological_validation_feature_importance_ablation.py

Optional:
    python 9_biological_validation_feature_importance_ablation.py --top-k 20
    python 9_biological_validation_feature_importance_ablation.py --no-shap

Labels:
    1 = independently curated positive compensation evidence
    0 = adequately tested negative evidence
    uncertain records must be excluded (e.g. label_numeric = -1).

This code requires enough independent positive/negative evidence and target
genes for grouped cross-validation. If those labels are not yet curated, it
will stop with a clear error rather than fabricate a model or metrics.
"""

from __future__ import annotations

import argparse
import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.ensemble import ExtraTreesClassifier, RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.metrics import (
    average_precision_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, accuracy_score, confusion_matrix,
    precision_recall_curve
)
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import Pipeline

warnings.filterwarnings("ignore", category=UserWarning)

ROOT = Path(__file__).resolve().parent
PAIR_FILE = ROOT / "features" / "candidate_gene_pairs.csv.gz"
LABEL_FILE = ROOT / "preprocessed" / "compensation_training_pairs.csv"
TERM_FILE = ROOT / "preprocessed" / "gene_function_terms.csv"
EXTERNAL_FILE = ROOT / "preprocessed" / "external_validation_pairs.csv"
CELLTYPE_FILE = ROOT / "preprocessed" / "celltype_predictions.csv"

OUT = ROOT / "downstream_validation"
FIG = OUT / "figures"
OUT.mkdir(parents=True, exist_ok=True)
FIG.mkdir(parents=True, exist_ok=True)

ID_COLS = {"target_gene", "candidate_gene", "candidate_source", "label",
           "label_numeric", "evidence_reference", "evidence_description",
           "curator_notes", "cell_type", "sample_id", "guide_identity"}

# Feature-group detection is prefix-based and can be extended to match
# the actual feature names in future sequence/network feature tables.
GROUP_PATTERNS = {
    "sequence": ("sequence_", "seq_", "paralog_", "homology_", "identity_"),
    "network": ("network_", "ppi_", "interaction_", "connectivity_", "degree_"),
    "expression": ("expression_", "target_expression_", "candidate_expression_"),
    "dependency": ("dependency_", "target_dependency_", "candidate_dependency_"),
    "functional": ("functional_", "go_", "pathway_", "ontology_"),
}


def read_table(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    if str(path).endswith(".gz"):
        return pd.read_csv(path, compression="gzip", low_memory=False)
    return pd.read_csv(path, low_memory=False)


def normalize_pair_columns(df: pd.DataFrame) -> pd.DataFrame:
    required = {"target_gene", "candidate_gene"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Missing pair identifier columns: {sorted(missing)}")
    df = df.copy()
    for c in ["target_gene", "candidate_gene"]:
        df[c] = df[c].astype(str).str.strip().str.upper().str.replace(r"\s*\(\d+\)$", "", regex=True)
    return df


def numeric_feature_columns(df: pd.DataFrame) -> list[str]:
    cols = []
    for c in df.columns:
        if c in ID_COLS:
            continue
        if pd.api.types.is_numeric_dtype(df[c]):
            cols.append(c)
    return cols


def detect_groups(feature_cols: list[str]) -> dict[str, list[str]]:
    groups = {}
    for group, prefixes in GROUP_PATTERNS.items():
        groups[group] = [
            c for c in feature_cols
            if c.lower().startswith(prefixes)
        ]
    return groups


def make_model(seed: int) -> Pipeline:
    # Tree ensembles accommodate nonlinear feature interactions and missing
    # values after median imputation. Class weighting helps with imbalance.
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median", add_indicator=True)),
        ("model", ExtraTreesClassifier(
            n_estimators=500,
            min_samples_leaf=2,
            max_features="sqrt",
            class_weight="balanced",
            n_jobs=-1,
            random_state=seed
        ))
    ])


def safe_binary_metrics(y_true, y_score, threshold=0.5):
    y_true = np.asarray(y_true, dtype=int)
    y_score = np.asarray(y_score, dtype=float)
    y_pred = (y_score >= threshold).astype(int)
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    tn, fp, fn, tp = cm.ravel()
    result = {
        "n": int(len(y_true)),
        "positives": int(y_true.sum()),
        "negatives": int((1-y_true).sum()),
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "mcc": float(matthews_corrcoef(y_true, y_pred)),
        "specificity": float(tn / (tn + fp)) if tn + fp else np.nan,
        "TN": int(tn), "FP": int(fp), "FN": int(fn), "TP": int(tp),
        "AUROC": float(roc_auc_score(y_true, y_score))
            if len(np.unique(y_true)) == 2 else np.nan,
        "AUPRC": float(average_precision_score(y_true, y_score))
            if len(np.unique(y_true)) == 2 else np.nan,
    }
    return result


def grouped_oof_predictions(X, y, groups, seed, n_splits):
    unique_groups = pd.Series(groups).nunique()
    class_counts = pd.Series(y).value_counts()
    if unique_groups < n_splits:
        raise ValueError(
            f"Only {unique_groups} target genes/groups; need at least "
            f"{n_splits} for StratifiedGroupKFold."
        )
    if len(class_counts) < 2 or class_counts.min() < n_splits:
        raise ValueError(
            "Not enough positive/negative labelled pairs for the requested "
            f"{n_splits}-fold grouped CV. Counts: {class_counts.to_dict()}"
        )

    cv = StratifiedGroupKFold(
        n_splits=n_splits, shuffle=True, random_state=seed
    )
    oof = np.full(len(y), np.nan, dtype=float)
    fold_rows = []
    fitted_models = []

    for fold, (tr, te) in enumerate(cv.split(X, y, groups), start=1):
        if len(np.unique(y[tr])) < 2 or len(np.unique(y[te])) < 2:
            raise ValueError(
                f"Fold {fold} lacks one class. Increase independent labelled "
                "target genes or reduce --folds."
            )
        model = make_model(seed + fold)
        model.fit(X.iloc[tr], y[tr])
        score = model.predict_proba(X.iloc[te])[:, 1]
        oof[te] = score
        row = safe_binary_metrics(y[te], score)
        row["fold"] = fold
        row["heldout_target_genes"] = int(pd.Series(groups).iloc[te].nunique())
        fold_rows.append(row)
        fitted_models.append((model, te))

    if np.isnan(oof).any():
        raise RuntimeError("Some labelled pairs did not receive OOF predictions.")
    return oof, pd.DataFrame(fold_rows)


def topk_known_validation(labelled, scores, top_k):
    tmp = labelled[["target_gene", "candidate_gene", "label_numeric"]].copy()
    tmp["oof_score"] = scores
    positive = tmp["label_numeric"].eq(1)
    rows = []
    for target, block in tmp.groupby("target_gene"):
        ranked = block.sort_values("oof_score", ascending=False)
        top = ranked.head(min(top_k, len(ranked)))
        n_known_pos = int(positive.loc[block.index].sum())
        hits = int(top["label_numeric"].eq(1).sum())
        rows.append({
            "target_gene": target,
            "candidate_pairs_evaluated": len(block),
            "known_positive_pairs": n_known_pos,
            f"positive_hits_top_{top_k}": hits,
            f"precision_top_{top_k}": hits / len(top) if len(top) else np.nan,
            f"recall_top_{top_k}": hits / n_known_pos if n_known_pos else np.nan
        })
    return pd.DataFrame(rows)


def function_similarity(predictions: pd.DataFrame, terms_path: Path) -> pd.DataFrame:
    if not terms_path.exists():
        print("[INFO] Gene function term file absent; functional similarity skipped.")
        return pd.DataFrame()
    terms = read_table(terms_path)
    if not {"gene", "term"}.issubset(terms.columns):
        raise ValueError("gene_function_terms.csv requires columns: gene, term")
    terms["gene"] = terms["gene"].astype(str).str.upper().str.strip()
    terms["term"] = terms["term"].astype(str).str.strip()
    gene_terms = terms.groupby("gene")["term"].apply(set).to_dict()

    out = predictions[["target_gene", "candidate_gene", "prediction_score"]].copy()
    shared_n, jaccard, shared_terms = [], [], []
    for a, b in zip(out.target_gene, out.candidate_gene):
        ta, tb = gene_terms.get(a, set()), gene_terms.get(b, set())
        inter, union = ta & tb, ta | tb
        shared_n.append(len(inter))
        jaccard.append(len(inter) / len(union) if union else np.nan)
        shared_terms.append(";".join(sorted(inter)))
    out["shared_function_term_count"] = shared_n
    out["functional_term_jaccard"] = jaccard
    out["shared_terms"] = shared_terms
    return out


def cross_celltype_reproducibility(path: Path, top_k: int) -> pd.DataFrame:
    if not path.exists():
        print("[INFO] Cell-type predictions absent; cross-cell-type reproducibility skipped.")
        return pd.DataFrame()
    df = normalize_pair_columns(read_table(path))
    required = {"cell_type", "prediction_score"}
    if required - set(df.columns):
        raise ValueError("celltype_predictions.csv requires cell_type and prediction_score.")
    df["pair"] = df["target_gene"] + "::" + df["candidate_gene"]
    ranks = []
    for ct, block in df.groupby("cell_type"):
        top = block.nlargest(top_k, "prediction_score")
        ranks.append((ct, set(top["pair"])))
    rows = []
    for i in range(len(ranks)):
        for j in range(i + 1, len(ranks)):
            c1, s1 = ranks[i]
            c2, s2 = ranks[j]
            union = s1 | s2
            rows.append({
                "cell_type_1": c1, "cell_type_2": c2,
                "top_k": top_k,
                "shared_top_pairs": len(s1 & s2),
                "top_k_jaccard": len(s1 & s2) / len(union) if union else np.nan
            })
    return pd.DataFrame(rows)


def external_validation(model, feature_cols, path: Path) -> dict | None:
    if not path.exists():
        print("[INFO] Independent-study file absent; external validation skipped.")
        return None
    ext = normalize_pair_columns(read_table(path))
    if "label" in ext.columns:
        ext["label_numeric"] = pd.to_numeric(ext["label"], errors="coerce")
    if "label_numeric" not in ext.columns:
        raise ValueError("External validation file requires label or label_numeric.")
    ext = ext[ext.label_numeric.isin([0, 1])].copy()
    missing = set(feature_cols) - set(ext.columns)
    if missing:
        raise ValueError(
            "External study lacks training feature columns: " + ", ".join(sorted(missing))
        )
    if ext.label_numeric.nunique() != 2:
        raise ValueError("External validation requires both positive and negative labels.")
    scores = model.predict_proba(ext[feature_cols])[:, 1]
    metrics = safe_binary_metrics(ext.label_numeric.astype(int), scores)
    ext["prediction_score"] = scores
    ext["prediction_class"] = (scores >= 0.5).astype(int)
    ext.to_csv(OUT / "external_validation_predictions.csv", index=False)
    return metrics


def run_ablation(labelled, y, groups_for_cv, all_features, feature_groups, seed, folds):
    configurations = {
        "sequence_only": feature_groups["sequence"],
        "network_only": feature_groups["network"],
        "expression_only": feature_groups["expression"],
        "dependency_only": feature_groups["dependency"],
        "sequence_plus_network": (
            feature_groups["sequence"] + feature_groups["network"]
        ),
        "integrated_available_groups": sum(
            [feature_groups[g] for g in
             ["sequence", "network", "expression", "dependency", "functional"]], []
        ),
        "complete_model_all_numeric_features": all_features,
    }

    rows = []
    for name, cols in configurations.items():
        cols = list(dict.fromkeys([c for c in cols if c in labelled.columns]))
        if not cols:
            rows.append({
                "configuration": name, "n_features": 0,
                "status": "NOT EVALUATED: feature group absent",
                "AUROC": np.nan, "AUPRC": np.nan, "MCC": np.nan
            })
            continue
        X = labelled[cols].replace([np.inf, -np.inf], np.nan)
        oof, _ = grouped_oof_predictions(
            X, y, groups_for_cv, seed, folds
        )
        m = safe_binary_metrics(y, oof)
        rows.append({
            "configuration": name, "n_features": len(cols),
            "status": "evaluated", **m
        })
    return pd.DataFrame(rows)


def plot_bar(df, x, y, title, path, horizontal=False):
    if df.empty or y not in df.columns:
        return
    d = df.dropna(subset=[y]).copy()
    if d.empty:
        return
    fig, ax = plt.subplots(figsize=(9, max(4, 0.28 * len(d))))
    if horizontal:
        d = d.sort_values(y)
        ax.barh(d[x].astype(str), d[y])
    else:
        ax.bar(d[x].astype(str), d[y])
        ax.tick_params(axis="x", rotation=35)
    ax.set_title(title)
    ax.set_xlabel(y)
    ax.grid(axis="x" if horizontal else "y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(path, format="svg", bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--top-k", type=int, default=20)
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-shap", action="store_true")
    args = parser.parse_args()

    print("=" * 72)
    print("CRLP BIOLOGICAL VALIDATION + FEATURE IMPORTANCE + ABLATION")
    print("=" * 72)

    pairs = normalize_pair_columns(read_table(PAIR_FILE))
    labels = normalize_pair_columns(read_table(LABEL_FILE))

    if "label_numeric" not in labels.columns:
        raise ValueError("Curated label file must contain label_numeric (1/0/-1).")
    labels["label_numeric"] = pd.to_numeric(labels["label_numeric"], errors="coerce")
    labels = labels[labels.label_numeric.isin([0, 1])].copy()
    labels = labels.drop_duplicates(["target_gene", "candidate_gene"])

    if labels.empty or labels.label_numeric.nunique() != 2:
        raise RuntimeError(
            "No usable curated positive AND negative compensation labels found. "
            "Complete compensation_evidence_annotated.csv and run "
            "2_define_compensation_labels.py first. Do not use the nine-model "
            "high-stress proxy labels as compensation ground truth."
        )

    pairs = pairs.drop_duplicates(["target_gene", "candidate_gene"])
    merged = labels.merge(
        pairs, on=["target_gene", "candidate_gene"], how="inner",
        validate="one_to_one"
    )
    if len(merged) < 20:
        raise RuntimeError(
            f"Only {len(merged)} labelled pairs overlap with feature table. "
            "Insufficient for meaningful grouped validation."
        )

    feature_cols = numeric_feature_columns(merged)
    if len(feature_cols) < 1:
        raise RuntimeError("No numeric pair-level features found.")

    groups = detect_groups(feature_cols)
    print(f"Curated labelled pairs overlapping feature table: {len(merged)}")
    print(f"Positive={int((merged.label_numeric == 1).sum())}; "
          f"Negative={int((merged.label_numeric == 0).sum())}")
    print("Detected feature groups:")
    for name, cols in groups.items():
        print(f"  {name}: {len(cols)}")
    print(f"  other numeric: {len(set(feature_cols) - set(sum(groups.values(), [])))}")

    y = merged.label_numeric.astype(int).to_numpy()
    X = merged[feature_cols].replace([np.inf, -np.inf], np.nan)
    target_groups = merged.target_gene.astype(str).to_numpy()

    # 1. Grouped out-of-fold evaluation by target gene (reduces leakage from
    # related candidate pairs sharing the same knockout/target gene).
    oof, fold_metrics = grouped_oof_predictions(
        X, y, target_groups, args.seed, args.folds
    )
    overall = safe_binary_metrics(y, oof)
    pd.DataFrame({"target_gene": merged.target_gene,
                  "candidate_gene": merged.candidate_gene,
                  "true_label": y, "oof_prediction_score": oof}).to_csv(
        OUT / "grouped_oof_pair_predictions.csv", index=False
    )
    fold_metrics.to_csv(OUT / "grouped_cv_metrics_by_fold.csv", index=False)
    with open(OUT / "grouped_oof_metrics.json", "w") as f:
        json.dump(overall, f, indent=2)

    # 2. Known compensation recovery among held-out (OOF) predictions.
    known = topk_known_validation(merged, oof, args.top_k)
    known.to_csv(OUT / "known_compensation_topk_validation.csv", index=False)

    # 3. Fit final model on all curated labels and score candidate pairs.
    final_model = make_model(args.seed)
    final_model.fit(X, y)
    candidate_features = pairs.copy()
    for c in feature_cols:
        if c not in candidate_features.columns:
            candidate_features[c] = np.nan
    candidate_features["prediction_score"] = final_model.predict_proba(
        candidate_features[feature_cols]
    )[:, 1]
    candidate_features["prediction_class_0_5"] = (
        candidate_features.prediction_score >= 0.5
    ).astype(int)

    known_pairs = set(zip(labels.target_gene, labels.candidate_gene))
    candidate_features["evidence_status"] = [
        "previously_curated" if (a, b) in known_pairs
        else "computational_hypothesis_not_experimentally_confirmed"
        for a, b in zip(candidate_features.target_gene,
                        candidate_features.candidate_gene)
    ]
    candidate_features.sort_values(
        "prediction_score", ascending=False
    ).to_csv(OUT / "all_ranked_candidate_predictions.csv", index=False)

    novel = candidate_features[
        candidate_features.evidence_status ==
        "computational_hypothesis_not_experimentally_confirmed"
    ].head(args.top_k)
    novel.to_csv(OUT / "top_novel_computational_hypotheses.csv", index=False)

    # 4. Functional similarity based on supplied GO/pathway term annotations.
    func = function_similarity(novel, TERM_FILE)
    if not func.empty:
        func.to_csv(OUT / "novel_candidate_functional_similarity.csv", index=False)

    # 5. Cross-cell-type reproducibility from independent per-cell-type scores.
    celltype = cross_celltype_reproducibility(CELLTYPE_FILE, args.top_k)
    if not celltype.empty:
        celltype.to_csv(OUT / "cross_celltype_topk_reproducibility.csv", index=False)

    # 6. Independent-study generalization. External labels must be curated
    # independently and features must be computed identically.
    ext_metrics = external_validation(final_model, feature_cols, EXTERNAL_FILE)
    if ext_metrics is not None:
        with open(OUT / "external_validation_metrics.json", "w") as f:
            json.dump(ext_metrics, f, indent=2)

    # 7. Permutation feature importance on grouped held-out folds.
    # Compute on each held-out fold model and average importance.
    imp_rows = []
    cv = StratifiedGroupKFold(
        n_splits=args.folds, shuffle=True, random_state=args.seed
    )
    for fold, (tr, te) in enumerate(cv.split(X, y, target_groups), start=1):
        model = make_model(args.seed + fold)
        model.fit(X.iloc[tr], y[tr])
        pi = permutation_importance(
            model, X.iloc[te], y[te], scoring="average_precision",
            n_repeats=10, random_state=args.seed + fold, n_jobs=-1
        )
        for col, mean, std in zip(feature_cols, pi.importances_mean,
                                   pi.importances_std):
            imp_rows.append({
                "fold": fold, "feature": col,
                "importance_mean_AUPRC_drop": float(mean),
                "importance_std": float(std)
            })
    imp = pd.DataFrame(imp_rows)
    imp_summary = imp.groupby("feature").agg(
        mean_AUPRC_drop=("importance_mean_AUPRC_drop", "mean"),
        sd_AUPRC_drop=("importance_mean_AUPRC_drop", "std")
    ).reset_index().sort_values("mean_AUPRC_drop", ascending=False)
    imp_summary.to_csv(OUT / "permutation_feature_importance.csv", index=False)
    plot_bar(
        imp_summary.head(25), "feature", "mean_AUPRC_drop",
        "Grouped-CV permutation feature importance",
        FIG / "permutation_feature_importance.svg", horizontal=True
    )

    # Group-level importance aggregation.
    group_imp = []
    for group, cols in groups.items():
        if cols:
            vals = imp_summary[imp_summary.feature.isin(cols)].mean_AUPRC_drop
            group_imp.append({
                "feature_group": group, "n_features": len(cols),
                "mean_feature_importance_sum": float(vals.sum()),
                "mean_feature_importance_average": float(vals.mean())
            })
    pd.DataFrame(group_imp).to_csv(
        OUT / "feature_group_importance.csv", index=False
    )

    # 8. Ablation study: same estimator, same grouped folds, same labels.
    ablation = run_ablation(
        merged, y, target_groups, feature_cols, groups,
        args.seed, args.folds
    )
    ablation.to_csv(OUT / "feature_group_ablation.csv", index=False)
    plot_bar(
        ablation[ablation.status == "evaluated"],
        "configuration", "AUPRC",
        "Feature-group ablation (grouped CV AUPRC)",
        FIG / "feature_group_ablation_auprc.svg"
    )

    # 9. Optional SHAP. Permutation importance above is the primary result.
    if not args.no_shap:
        try:
            import shap
            sample = X.sample(min(500, len(X)), random_state=args.seed)
            fitted = make_model(args.seed)
            fitted.fit(X, y)
            transformed = fitted.named_steps["imputer"].transform(sample)
            explainer = shap.TreeExplainer(fitted.named_steps["model"])
            sv = explainer.shap_values(transformed)
            # For binary classifiers SHAP may return list[class] or ndarray.
            arr = sv[1] if isinstance(sv, list) else sv
            shap.summary_plot(
                arr, show=False, max_display=25,
                feature_names=feature_cols
            )
            plt.tight_layout()
            plt.savefig(FIG / "shap_summary.svg", format="svg", bbox_inches="tight")
            plt.close()
            print("[OK] SHAP summary saved.")
        except ImportError:
            print("[INFO] SHAP is not installed; permutation importance remains available.")
        except Exception as e:
            print(f"[WARNING] SHAP was skipped: {e}")

    # 10. Record availability and interpretation boundaries.
    availability = {
        "sequence_features_available": bool(groups["sequence"]),
        "network_features_available": bool(groups["network"]),
        "expression_features_available": bool(groups["expression"]),
        "dependency_features_available": bool(groups["dependency"]),
        "functional_features_available": bool(groups["functional"]),
        "external_validation_available": EXTERNAL_FILE.exists(),
        "cross_celltype_predictions_available": CELLTYPE_FILE.exists(),
        "gene_function_terms_available": TERM_FILE.exists(),
        "novel_predictions_are_experimental_facts": False,
        "classification_target": "independently curated compensation evidence labels",
        "cv": f"{args.folds}-fold StratifiedGroupKFold grouped by target_gene"
    }
